import { mkdir, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import { formatExitMessage } from './messages.js';
import { validatorDir } from '../util/paths.js';
import { assertInsideProject } from '../util/containment.js';
import { SEMANTIC_CHECK_IDS } from '../types.js';
import type {
  AppliedFixRecord,
  CheckId,
  Finding,
  PostFixSuiteOutcome,
  ReportFileEntry,
  ReportGeneratedTest,
  RevertedFixRecord,
  RunReport,
} from '../types.js';

export const REPORT_HTML_FILE = 'report.html';

export interface RenderHtmlReportOptions {
  /**
   * Project root absolute path. Used solely to derive the human-readable
   * project name shown in the `<title>` and `<h1>` summary. Not embedded
   * elsewhere in the document.
   */
  readonly projectRoot: string;
  /**
   * Optional CLI version string (e.g. `"0.2.1"`). When present it is shown
   * in the footer ("Generated by sapui5-validate v<version>"). When omitted
   * the footer simply says "Generated by sapui5-validate". The writer
   * derives this from package.json; tests pass it explicitly so the unit
   * suite stays free of fs reads.
   */
  readonly version?: string;
}

/**
 * Render a complete HTML5 document for a `RunReport`. Pure function: no fs,
 * no env reads, no time-of-day dependencies. The output string starts with
 * `<!DOCTYPE html>` and ends with `</html>\n`.
 */
export function renderHtmlReport(
  report: RunReport,
  options: RenderHtmlReportOptions,
): string {
  const projectName = projectDisplayName(options.projectRoot);
  const titleText = `SAPUI5 Validator Report — ${projectName}, ${formatTimestamp(report.finishedAt)}`;
  const exitMessage = formatExitMessage(report.exitReason) ?? 'Success.';

  const summaryLine = renderSummaryLine(report);
  const appliedSection = renderAppliedFixesSection(report.files);
  const revertedSection = renderRevertedFixesSection(report.files);
  const baselineSection = renderBaselineFindingsSection(report.files);
  const checkSection = renderCheckFindingsSection(report.files);
  // COR-8: the primary outputs of a `generate` run (which tests passed /
  // quarantined) and the safety-critical post-fix-suite outcome of a `validate`
  // run. Each returns '' when not applicable and is filtered out below.
  const generatedSection = renderGeneratedTestsSection(report.generatedTests);
  const postFixSection = renderPostFixSuiteSection(report.postFixSuite);

  return [
    '<!DOCTYPE html>',
    '<html lang="en">',
    '<head>',
    '  <meta charset="UTF-8">',
    `  <title>${escapeHtml(titleText)}</title>`,
    '  <style>',
    INLINE_CSS,
    '  </style>',
    '</head>',
    '<body>',
    '  <main>',
    renderHeader(report, projectName, exitMessage),
    summaryLine,
    appliedSection,
    revertedSection,
    generatedSection,
    postFixSection,
    baselineSection,
    checkSection,
    renderFooter(options.version),
    '  </main>',
    '</body>',
    '</html>',
  ]
    .filter((s) => s.length > 0)
    .join('\n') + '\n';
}

/**
 * Render and write `report.html` to `<projectRoot>/.sapui5-validator/report.html`.
 * Returns the absolute path of the file that was written. Mirrors
 * `writeReport`'s lifecycle: same parent directory, same trailing newline
 * convention. Callers are expected to handle / swallow failures the same way
 * they do for `writeReport` (the orchestrator treats both as non-blocking).
 */
export async function writeHtmlReport(
  projectRoot: string,
  report: RunReport,
): Promise<string> {
  const target = join(validatorDir(projectRoot), REPORT_HTML_FILE);
  // v0.8.1 V1: `.sapui5-validator/` can be a committed link out of the tree.
  await assertInsideProject(target, projectRoot);
  await mkdir(dirname(target), { recursive: true });
  const html = renderHtmlReport(report, {
    projectRoot,
    ...(CLI_VERSION !== undefined ? { version: CLI_VERSION } : {}),
  });
  await writeFile(target, html, 'utf8');
  return target;
}


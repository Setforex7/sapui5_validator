/**
 * V1.2-6 / V1.2-7 (Feature 3 — HTML report). Pure renderer + file writer for
 * a self-contained, single-file HTML view of a `RunReport`.
 *
 * Why a separate module:
 *   - `report.json` is the canonical machine-readable artifact. The HTML is a
 *     presentation layer: optional (`--html` opt-in), schema-free, and never
 *     consumed back into the orchestrator. Keeping it isolated avoids
 *     entangling the JSON schema with display concerns.
 *
 * Design constraints (V1.2-PLAN.md Feature 3 + V1.2-6 / V1.2-7 briefs):
 *   - No new npm dependencies. Template literals, `escapeHtml`, and built-in
 *     `Intl.DateTimeFormat` only.
 *   - No JavaScript in the output. `<details>/<summary>` is the only
 *     disclosure primitive.
 *   - Self-contained: inline CSS, no external assets, opens in any browser.
 *   - Exit-reason text comes from `formatExitMessage` (single source of truth
 *     for human-readable exit text — shared with the CLI's stderr surface).
 *
 * V1.2-7 visual refinements (in order of effect on the layout):
 *   1. Section order under <main>: header → summary line → applied fixes →
 *      reverted fixes → baseline findings → check findings → footer. The two
 *      "what the run did" sections lead; informational sections follow.
 *   2. Summary line of metric pills (fixes applied / reverted / findings /
 *      LLM calls / optional capped-by-cap count) sits directly below the
 *      header for at-a-glance scanning.
 *   3. Check Findings are grouped first by checkId, then by file. Baseline
 *      findings keep per-file grouping (they are typically few and the
 *      category dimension is less useful there).
 *   4. Findings with a `proposedFix` render <details open>; prose-only
 *      findings (proposedFix === null, e.g. missing-test-coverage) render
 *      collapsed. This stops the dominant prose-only category from drowning
 *      out actionable fix candidates.
 *   5. `startedAt` / `finishedAt` render via `Intl.DateTimeFormat('en-GB')`
 *      with a "(local time)" suffix; `durationMs` renders as "X min Y sec"
 *      / "X sec" / "X ms" depending on magnitude.
 *   6. Inline CSS color palette is now documented and deliberate (green for
 *      applied, amber for reverted / capped, neutral gray for baseline, blue
 *      accent for the LLM-driven check section).
 *
 * Deviations from the V1.2-6 brief (preserved):
 *   1. Output path is `.sapui5-validator/report.html` (sits next to
 *      `report.json`, both written by the same `validatorDir`-based
 *      resolver). The brief's mention of `.sapui5-validator/last-run/` is
 *      based on the misconception that `report.json` lives under
 *      `last-run/`; it does not.
 *   2. `renderHtmlReport` takes a second `RenderHtmlReportOptions` argument
 *      so the title can show the project basename (RunReport carries no
 *      `projectRoot` field and bumping the schema is out of V1.2 scope).
 */

